// Заполняем select'ы при загрузке. Целевой язык не должен иметь 'auto'.
(function initLangs() {
  function fill(select, includeAuto, defaultCode) {
    if (!select) return;
    window.LANGS.forEach(function (pair) {
      if (!includeAuto && pair[0] === "auto") return;
      const opt = document.createElement("option");
      opt.value = pair[0];
      opt.textContent = pair[1];
      select.appendChild(opt);
      if (pair[0] === defaultCode) opt.selected = true;
    });
  }
  document.addEventListener("DOMContentLoaded", function () {
    fill(document.getElementById("srcLang"), true,  "auto");
    fill(document.getElementById("dstLang"), false, "ru");
  });
})();
